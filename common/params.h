// ============================================================
// 视频广播项目 - 两端共享参数约定
// ============================================================
//
// 这个头文件是发送端和接收端的"合同"：两端编译时都 include 它，
// 任何参数只在这里定义一次。好处：改分辨率/码率/端口只动这一个文件，
// 两端同时生效，不会出现"发送端按 720p 编码、接收端按 480p 解码"的错位。
// （运行时的动态约定交给 SDP 文件，后面推流那节会讲到）
//
// 参数总览:
//   分辨率: 640x480    帧率: 30 fps    码率: 2 Mbps
//   编码:   H.264      传输: RTP over UDP（RTP 是什么见下面传输参数开头的说明）
//   端口:   5004       组播: 239.255.0.1
// ============================================================
//
// ============================================================
// 读前补课：读懂本文件需要的两个视频概念
// ============================================================
//
// 【概念一：I 帧和 P 帧】
// 视频能压缩约 100 倍的核心秘密 = 相邻帧之间高度相似（上一帧和下一帧
// 只差一点点）。所以编码器不每帧都存完整画面，而是分三种帧：
//
//   I 帧（Intra frame，关键帧）
//     = 存完整画面，像一张 JPEG 照片，单独就能解码。
//     特点：大（一帧可能几十 KB）；是"锚点"——网络丢包花屏后，
//     解码器只能等下一个 I 帧重新从头解，画面才恢复完整。
//     所以 kGopSize（I 帧间隔）决定了"花屏后几秒自恢复"。
//
//   P 帧（Predictive frame，预测帧）
//     = 只存"和上一帧的差异"（比如"白块右移了 8 像素"）。
//     特点：小（通常只有几 KB）；必须从上一个 I 帧一路解过来，
//     中途缺了参考帧就可能花屏。压缩率主要靠它。
//
//   B 帧（Bidirectional frame，双向预测帧）
//     = 同时参考前后两帧，压缩率最高，但编码端要等"未来帧"到手
//     才能编 = 引入延迟，本项目不用它。
//
// 从上一个 I 帧到下一个 I 帧之前的一组帧叫 GOP（见下面 kGopSize）。
//
// 【概念二：码率】
// 码率 = 视频流每秒的数据量 = 编码器的"画质预算"。
//   单位是 bit/秒：本项目的 2Mbps = 每秒 2,000,000 bit。
//   单位换算（易混点）：网络行业用 bit（Mbps），文件大小用 Byte——
//   1 Byte = 8 bit，所以 2Mbps ÷ 8 = 250KB/秒。

//   原始画面 640x480x3字节 x 30帧 ≈ 27MB/秒，压到 2Mbps ≈ 250KB/秒，
//   缩小约 100 倍。这个压缩是后面的 H.264 编码完成的，读到那里再细看。

//   码率是"平均值"：I 帧大、P 帧小，编码器内部做码率控制
//   （rate control），让一秒钟内所有帧加起来平均 ≈ 250KB（见 kBitRate）。

//   码率 vs 分辨率：分辨率是画面有多少像素格（空间密度），码率是每秒
//   多少数据去填这些格（时间流量）。码率不变时分辨率越高反而越糊。
//
// 【概念三：RTP 是什么】
// RTP = 实时传输协议 = 音视频发到网上时的"打包格式"：
// 规定每个包装多少数据、包按什么顺序编号、带什么时间戳。
// 类比快递：RTP 是纸箱和面单的标准（面单写第几箱、几点发出），
// UDP 是快递车。本项目里：FFmpeg 把 H.264 码流切成 RTP 包发出去，
// 接收端按面单把包拼回 H.264（收流那节会细讲）。
// ============================================================
#pragma once

#include <cstdint>
#include <string_view>

namespace vb
{
// ---- 画面参数 ----
// 【本小节要用的两个概念，先看这里】
// ① I 帧和 P 帧：视频能压缩约 100 倍的核心秘密 = 相邻帧之间高度相似
//    （上一帧和下一帧只差一点点），所以编码器不每帧都存完整画面：
//    I 帧 = 存完整画面（像一张 JPEG），单独就能解码；大，是"锚点"——
//      丢包花屏后要等下一个 I 帧才能恢复完整画面。
//    P 帧 = 只存"和上一帧的差异"（比如"白块右移了 8 像素"）；小，
//      必须从上一个 I 帧一路解过来，中途缺参考帧就可能花屏。
//    B 帧 = 同时参考前后两帧，压缩率最高，但编码端要等"未来帧"= 延迟，
//      本项目不用它。
// ② 码率 = 视频流每秒的数据量 = 编码器的"画质预算"，单位 bit/秒。
//    易混点：网络行业用 bit（Mbps），文件用 Byte，1 Byte = 8 bit，
//    所以 2Mbps ÷ 8 = 250KB/秒。码率是"平均值"：I 帧大 P 帧小，
//    编码器内部做码率控制，让每秒所有帧加起来平均 ≈ 250KB。
//
// 分辨率 = 画面横向 x 纵向的像素格数。
//
// 先铺垫一个数字：摄像头原始画面每秒 27MB，网络扛不住，要用 H.264
// 压成 250KB 才发（27MB = 900KB/帧 x 30 帧；250KB/秒 = 2Mbps ÷ 8）。
//
// 为什么选 640x480（约 30 万像素）？
// 1. 码率预算：系统码率定在 2Mbps（约 250KB/秒）。分辨率越高，
//    每个像素分到的数据越少——1080p 用 2Mbps 反而比 640x480 用 2Mbps糊；
// 2. 算力：信创平台 CPU 偏弱，软编要跟上 30fps，这个尺寸是甜点位；
// 3. 场景：电子教室/培训室看课件和桌面，480p 足够看清文字。
inline constexpr int kWidth = 640;
inline constexpr int kHeight = 480;

// 帧率 30fps = 每秒 30 张画面，即"每帧间隔约 33 毫秒"。
inline constexpr int kFrameRate = 30;

// 码率 2Mbps = 每秒 2,000,000 bit（÷8 = 250KB/秒，概念见本小节开头）。
inline constexpr int kBitRate = 2'000'000;

// GOP = Group of Pictures = 两个 I 帧之间隔多少帧。
// GOP 60 的意思是帧序列长这样：I 帧 → 59 个 P 帧 → I 帧 → 59 个 P 帧 → …
// 60 帧 ÷ 每秒 30 帧 = 每 2 秒出现一个 I 帧。
// 这个数字决定"自恢复时间"：丢包或半路收流时 P 帧解不出、画面花屏，
// 只能等下一个 I 帧从头解——所以最多 2 秒画面自动恢复。
inline constexpr int kGopSize = 60;

// ---- 传输参数 ----
// 【本小节要用的概念：RTP】
// RTP = 实时传输协议 = 音视频发到网上时的"打包格式"：
// 规定每个包装多少数据、包按什么顺序编号、带什么时间戳。
// 类比快递：RTP 是纸箱和面单的标准（面单写第几箱、几点发出），
// UDP 是快递车。本项目里：FFmpeg 把 H.264 码流切成 RTP 包发出去，
// 接收端按面单把包拼回 H.264（收流那节会细讲）。
//
// UDP 端口 5004：视频流走 UDP 收发的那个端口，5004 是 RTP 的惯例默认值。
// 为什么类型是 uint16_t：协议里端口号固定占 2 字节，所以用"钉死位数"
// 的类型——uint16_t = 刚好 2 字节的整数（0~65535）。普通 int 占几字节
// 由编译器/平台决定（不固定），网络数据结构不能靠它。
// 这一类类型的全家：uint8_t = 1 字节（0~255）、uint16_t = 2 字节、
// uint32_t = 4 字节（0~约 42 亿），下面 RtpHeader 结构体里会用到。
// 部署时防火墙需放行：sudo ufw allow 5004/udp
inline constexpr uint16_t kUdpPort = 5004;

// 组播地址 239.255.0.1：
// IP 地址不是随便用的，某些段有专门用途——凡是以 239 开头的地址
// （写成 239.0.0.0/8，/8 = 只看开头 8 位）都被划为"组播保留段"，
// 只在本地网络内使用，路由器不把它们转发到公网——正好适合
// 教室/培训室这种内网广播场景。
// 组播原理：发送端只发一份数据到这个地址，沿途交换机/路由器负责
// 复制给每个"加入该组"的接收端——所以发送端负载与接收端数量解耦。
inline constexpr std::string_view kDefaultMulticastAddress = "239.255.0.1";

// RTP payload type（负载类型，简称 PT）96：
// RTP 每个包的面单上带一个数字，告诉接收端"这个包里装的是什么编码"——
// 网络上可能同时跑音频流和视频流，接收端靠这个数字决定把包送给哪个解码器。
// 0-95 号预先定给了固定编码（如 0 号 = 电话音频），96-127 是自由区：
// 装什么由收发双方自己约定，H.264 大家习惯用 96 号。
// 本项目用 96 并写进 SDP，告诉接收端"96 号包 = H.264"。
inline constexpr int kPayloadTypeH264 = 96;

// 早期手写 RTP 阶段的两个常量。现在分包由 FFmpeg rtp muxer（muxer =
// 封装器，把数据打包成 RTP 包的模块）代劳，这两个常量连同下面
// RtpHeader 结构体都已不再使用，留着作参考：
//
// kRtpHeaderSize = 12
//   一个 RTP 包开头固定 12 字节的"面单"（头），记录序号/时间戳等信息
//   （具体字段见下面 RtpHeader 结构体）。
//
// kRtpMaxPacketSize = 1400
//   一个 RTP 包最多装 1400 字节数据。为什么取 1400：
//   网络上一个数据包最多 1500 字节（以太网标准）。
//   现在这 1500 里要先扣掉 IP 和 UDP 两层各加的地址信息（IP 头 20 字节 +
//   UDP 头 8 字节），1500 - 20 - 8 = 1472 是"不切包"的上限；
//   取 1400 再留点余量，避免 IP 分片（分片 = 包太大被切成几小片传，
//   只要丢一小片整个包就白传了，等于放大丢包的影响）。
inline constexpr int kRtpHeaderSize = 12;
inline constexpr int kRtpMaxPacketSize = 1400;

// 早期手写 RTP 分包用的头部结构体（现由 FFmpeg 代劳，未使用）。
// （uint8_t/uint16_t/uint32_t 这类类型是什么，见上面 kUdpPort 的注释）
// RTP 头共 12 字节，由 5 个字段组成，大小相加：1 + 1 + 2 + 4 + 4 = 12。
// 每个字段是干什么的：
//
//   v_p_x（1 字节）
//     1 字节 = 8 个二进制位，这里被切成 4 小块挤在一起（省字节）：
//     版本号(2位) | 填充标志(1位) | 扩展标志(1位) | 来源个数(4位)
//     —— 2+1+1+4 正好凑满 8 位
//
//   marker_payloadType（1 字节）
//     第 1 位是标记位（视频帧最后一个分片时置 1，告诉接收端"这帧收全了"），
//     后 7 位是负载类型 PT（上面讲过的"包里装的是什么编码"）
//
//   seq（2 字节）       包序号：接收端靠它检测丢包和乱序
//   timestamp（4 字节） 采样时间戳：同一帧的多个分片时间戳相同
//   ssrc（4 字节）      流标识：区分同一会话中的不同来源
struct RtpHeader
{
    uint8_t v_p_x; // 版本号(2位) | 填充标志(1位) | 扩展标志(1位) | 来源个数(4位)
    uint8_t marker_payloadType;
    uint16_t seq;
    uint32_t timestamp;
    uint32_t ssrc;
};

} // namespace vb
